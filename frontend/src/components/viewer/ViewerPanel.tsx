const ModelViewer = lazy(() => import('./ModelViewer'))

function ViewerEmpty() {
  const activeJob = useJobStore(selectActiveJob)
  const hasImages = useReferenceStore((s) => (s.set?.images.length ?? 0) > 0)
  const reachable = useSystemStore((s) => s.reachable)

  if (activeJob && !isTerminal(activeJob)) {
    const progress = activeJob.progress
    return (
      <div className={styles.empty}>
        <div className={`${styles.emptyIcon} ${styles.emptyIconActive}`}>
          <LoaderCircle size={26} className={styles.spin} aria-hidden />
        </div>
        <p className={styles.emptyTitle}>
          {activeJob.status === 'queued' ? 'Waiting in queue…' : `${progress.stage_label}…`}
        </p>
        <div className={styles.emptyProgress}>
          <ProgressBar value={progress.percent} label="Generation progress" />
          <span className="mono">{Math.round(progress.percent)}%</span>
        </div>
        <p className={styles.emptyText}>The model appears here as soon as it is ready.</p>
      </div>
    )
  }

  return (
    <div className={styles.empty}>
      <div className={styles.emptyIcon}>
        <Box size={26} aria-hidden />
      </div>
      <p className={styles.emptyTitle}>No model to display</p>
      {reachable === false ? (
        <p className={styles.emptyText}>The backend is offline. Generated models will appear here once it reconnects.</p>
      ) : (
        <ol className={styles.steps}>
          <li className={hasImages ? styles.stepDone : undefined}>
            <ImagePlus size={14} aria-hidden /> Add a reference image (a clean front view works best)
          </li>
          <li>
            <Sparkles size={14} aria-hidden /> Click <strong>Generate 3D model</strong> (Ctrl+Enter)
          </li>
          <li>
            <MousePointer2 size={14} aria-hidden /> Orbit, zoom and inspect — then download the GLB
          </li>
        </ol>
      )}
    </div>
  )
}

const VARIANT_TITLE = {
  original: 'Model generated by TRELLIS.2',
  tunedReady: 'Mesh repaired and refined by Auto Tune',
  tunedMissing: 'Run Auto Tune to create a tuned version',
} as const

/** Original | Tuned toggle over the canvas, with the tuned model's own loading / error state. */
function VariantBar({ variant, hasTuned }: { variant: ModelVariant; hasTuned: boolean }) {
  const setVariant = useMeshTunerStore((s) => s.setVariant)
  const secondaryStatus = useViewerRuntime((s) => s.secondaryStatus)
  const loaded = useViewerRuntime((s) => s.secondaryLoadedBytes)
  const total = useViewerRuntime((s) => s.secondaryTotalBytes)
  const retrySecondary = useViewerRuntime((s) => s.retrySecondary)
  const tunedSelected = variant === 'tuned'

  return (
    <div className={styles.variantBar}>
      <div className={styles.variantControl}>
        <SegmentedControl<ModelVariant>
          label="Model version"
          size="sm"
          value={variant}
          options={[
            { value: 'original', label: 'Original', title: VARIANT_TITLE.original },
            {
              value: 'tuned',
              label: 'Tuned',
              title: hasTuned ? VARIANT_TITLE.tunedReady : VARIANT_TITLE.tunedMissing,
              disabled: !hasTuned,
            },
          ]}
          onChange={setVariant}
        />
      </div>
      {tunedSelected && secondaryStatus === 'loading' && (
        <span className={styles.variantChip} role="status">
          <Spinner size={11} />
          Loading tuned model{total > 0 ? ` ${Math.round((loaded / total) * 100)}%` : '…'}
        </span>
      )}
      {tunedSelected && secondaryStatus === 'error' && (
        <span className={`${styles.variantChip} ${styles.variantError}`} role="alert">
          Tuned model failed to load
          {retrySecondary && (
            <button type="button" className={styles.variantRetry} onClick={() => retrySecondary()}>
              Retry
            </button>
          )}
        </span>
      )}
    </div>
  )
}

/** 3D viewer card: lazy R3F canvas, overlay toolbar, empty/progress states, fullscreen and screenshots. */
export function ViewerPanel({ active = true }: { active?: boolean }) {
  const job = useJobStore(selectViewedJob)
  const options = useUiStore((s) => s.viewer)
  const { latestRun, tunedRun, variant } = useViewedTuning()
  const breakpoint = useBreakpoint()
  const containerRef = useRef<HTMLElement>(null)
  const [api, setApi] = useState<ViewerApi | null>(null)
  const [mountedTunedUrl, setMountedTunedUrl] = useState<string | null>(null)
  const { isFullscreen, toggle, supported } = useFullscreen(containerRef)

  const result = job?.status === 'completed' ? job.result : null
  const url = result ? jobModelUrl(result) : null
  const tunedUrl = tunedRun ? tunedModelUrl(tunedRun.result) : null
  const showTuned = variant === 'tuned' && tunedUrl !== null
  // Phones mount the tuned model only once it was shown (memory); larger screens preload it for an instant toggle.
  if (showTuned && mountedTunedUrl !== tunedUrl) setMountedTunedUrl(tunedUrl)
  const secondaryUrl = tunedUrl && (breakpoint !== 'mobile' || mountedTunedUrl === tunedUrl) ? tunedUrl : null
  const tunedFaces = tunedRun?.result.stats?.faces ?? null

  const screenshot = () => {
    const dataUrl = api?.screenshot()
    if (!dataUrl || !job) {
      toast.error('Screenshot failed', 'The viewer is not ready yet.')
      return
    }
    const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)
    saveUrl(dataUrl, `img3d_${job.id}${showTuned ? '_tuned' : ''}_${options.viewMode}_${stamp}.png`)
  }

  return (
    <section ref={containerRef} className={`${styles.viewer} ${isFullscreen ? styles.fullscreen : ''}`} aria-label="3D viewer">
      <div className={styles.stage}>
        {url ? (
          <ViewerErrorBoundary key={url}>
            <Suspense
              fallback={
                <div className={styles.chunkLoading}>
                  <Spinner size={18} />
                  <span>Loading 3D viewer…</span>
                </div>
              }
            >
              <ModelViewer
                key={url}
                url={url}
                secondaryUrl={secondaryUrl}
                showSecondary={showTuned}
                options={options}
                active={active}
                onApi={setApi}
              />
            </Suspense>
          </ViewerErrorBoundary>
        ) : (
          <ViewerEmpty />
        )}
      </div>

      <ViewerToolbar
        disabled={!url || !api}
        isFullscreen={isFullscreen}
        fullscreenSupported={supported}
        onResetCamera={() => api?.resetCamera()}
        onScreenshot={screenshot}
        onToggleFullscreen={() => void toggle()}
      />

      {url && (tunedRun || latestRun) && <VariantBar variant={variant} hasTuned={tunedRun !== null} />}

      {job && result && (
        <div className={styles.caption}>
          <span className={styles.captionId}>
            {job.id}
            {showTuned ? ' · tuned' : ''}
          </span>
          <span>{formatCompact(showTuned && tunedFaces !== null ? tunedFaces : result.stats.faces)} tris</span>
        </div>
      )}
    </section>
  )
}
